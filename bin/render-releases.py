#!/usr/bin/env python3
# Spencer Butler <dev@tcos.us>
# render-releases.py
# Renders the "Releases" table on the org profile README from GitHub itself:
# every org repo with a GitHub Release, its latest version, date and notes
# link. Generated, never typed (operator, 2026-09-06: "update the main tcos
# page with a list of all of our released repos").
#
#   bin/render-releases.py            print the table
#   bin/render-releases.py --write    splice it into profile/README.md between the markers
#   bin/render-releases.py --check    exit 1 if the README is stale (CI)
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

ORG = "Twin-Cities-Open-Systems"
README = Path(__file__).resolve().parents[1] / "profile" / "README.md"
START, END = "<!-- releases:start -->", "<!-- releases:end -->"


def gh(path: str):
    r = subprocess.run(["gh", "api", "--paginate", path], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"render-releases: gh api {path} failed: {r.stderr.strip()[-200:]}")
    out = r.stdout.strip()
    # --paginate concatenates JSON arrays; join them
    if out.startswith("["):
        items = []
        for chunk in re.split(r"\]\s*\[", out.strip("[]")):
            if chunk.strip():
                items.extend(json.loads("[" + chunk + "]"))
        return items
    return json.loads(out)


def collect() -> list[dict]:
    rows = []
    for repo in gh(f"orgs/{ORG}/repos?per_page=100&type=all"):
        if repo.get("archived"):
            continue
        r = subprocess.run(["gh", "api", f"repos/{ORG}/{repo['name']}/releases/latest"], capture_output=True, text=True)
        if r.returncode != 0:
            continue                                    # no release: not listed, by definition
        rel = json.loads(r.stdout)
        rows.append({
            "repo": repo["name"], "private": repo["private"], "description": (repo.get("description") or "").strip(),
            "version": rel["tag_name"], "date": (rel.get("published_at") or rel.get("created_at") or "")[:10],
            "url": rel["html_url"], "semver": bool(re.fullmatch(r"v\d+\.\d+\.\d+", rel["tag_name"])),
        })
    rows.sort(key=lambda x: (not x["semver"], x["repo"]))
    return rows


def render(rows: list[dict]) -> str:
    lines = ["| repo | latest | released | what |", "|---|---|---|---|"]
    for x in rows:
        # the repo column links to its releases page: a release page has no relative form,
        # and the org's link check exempts it (a bare repo link would have to be relative)
        name = f"[{x['repo']}](https://github.com/{ORG}/{x['repo']}/releases)" if not x["private"] else f"{x['repo']} 🔒"
        ver = f"[{x['version']}]({x['url']})" if not x["private"] else x["version"]
        lines.append(f"| {name} | {ver} | {x['date']} | {x['description']} |")
    lines.append("")
    lines.append(f"_{len(rows)} repos with a release; semver ones first. Generated by `bin/render-releases.py` from GitHub Releases; "
                 "a repo appears here the moment `hee release promote` publishes it._")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    table = render(collect())
    text = README.read_text()
    if START not in text or END not in text:
        sys.exit(f"render-releases: {README} has no {START} / {END} markers")
    new = re.sub(re.escape(START) + r".*?" + re.escape(END), START + "\n" + table + "\n" + END, text, flags=re.S)
    if "--write" in argv:
        README.write_text(new); print(f"OK wrote {README.relative_to(README.parents[2])}: {table.count(chr(10)) - 3} row(s)")
        return 0
    if "--check" in argv:
        if new != text:
            print("🔴 CRITICAL render-releases: profile/README.md releases table is stale -- run bin/render-releases.py --write"); return 1
        print("🟢 OK render-releases: profile/README.md releases table is current"); return 0
    print(table); return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
